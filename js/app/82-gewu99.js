  _gw99Goto(shelfId) {
    this._gw99Settle();
    const sh = LIB99_SHELVES.find(x => x.id === shelfId);
    if (!sh) return;
    this._gw99View = 'shelf';
    this._gw99Shelf = sh.id;
    this._gw99Book = null;
    this.gotoWb('gewu99');
  },
  _gw99Open(shelfId, bookId) {
    const sh = LIB99_SHELVES.find(x => x.id === shelfId);
    if (!sh) return;
    const b = sh.books.find(x => x.id === bookId);
    if (!b) return;
    this._gw99View = 'read';
    this._gw99Shelf = sh.id;
    this._gw99Book = b.id;
    const prog = this._gw99Progress();
    this._gw99Flat = (prog[sh.id + '_' + b.id] || {}).flat || 0;
    this._gw99StartClock();
    this.gotoWb('gewu99');
  },
  _gw99Back() {
    this._gw99Settle();
    this._gw99View = 'shelves';
    this._gw99Shelf = null;
    this._gw99Book = null;
    this.gotoWb('gewu99');
  },
  _gw99Leave() {
    // 合上书：结算阅读时长，回到该书所在书架
    this._gw99Settle();
    this._gw99View = 'shelf';
    this._gw99Book = null;
    this.gotoWb('gewu99');
  },
  _gw99Jump(gi) {
    this._gw99TurnTo(gi);
  },
  _gw99Turn(dir) {
    const book = this._gw99CurBook();
    if (!book) return;
    const flat = this._gw99FlatBook(book);
    const ni = Math.max(0, Math.min(flat.length - 1, this._gw99Flat + dir));
    this._gw99TurnTo(ni, dir);
  },
  _gw99TurnTo(ni, dir) {
    const book = this._gw99CurBook();
    if (!book) return;
    if (ni === this._gw99Flat) return;
    const flat = this._gw99FlatBook(book);
    this._gw99Flat = Math.max(0, Math.min(flat.length - 1, ni));
    // 翻页动画：旧页快照翻走（CSS 3D），随后渲染新页
    try {
      const pageEl = document.getElementById('gw99Page');
      if (pageEl) {
        const sheet = document.createElement('div');
        sheet.className = 'gw-sheet' + (dir >= 0 ? ' gw-sheet-next' : ' gw-sheet-prev');
        sheet.innerHTML = pageEl.innerHTML;
        pageEl.parentNode.appendChild(sheet);
        setTimeout(() => { try { sheet.remove(); } catch (e) {} }, 480);
      }
    } catch (e) {}
    this.gotoWb('gewu99');
    this._gw99SavePos();
  },
  _gw99CurShelf() { return LIB99_SHELVES.find(x => x.id === this._gw99Shelf) || null; },
  _gw99CurBook() {
    const sh = this._gw99CurShelf();
    return sh ? sh.books.find(b => b.id === this._gw99Book) : null;
  },
  _gw99SavePos() {
    const book = this._gw99CurBook();
    if (!book) return;
    const prog = this._gw99Progress();
    const key = this._gw99Shelf + '_' + book.id; // 书 id 跨书架不唯一（多个书架有 zb/ky），用复合键
    const p = prog[key] || { flat: 0, sec: 0 };
    p.flat = this._gw99Flat;
    p.last = Date.now();
    prog[key] = p;
    this._gw99ProgressSave(prog);
  },

  // ==================== 书角正计时 ====================
  _gw99StartClock() {
    this._gw99StopClock();
    this._gw99T0 = Date.now();
    this._gw99Timer = setInterval(() => this._gw99ClockTick(), 1000);
  },
  _gw99ClockTick() {
    try {
      const el = document.getElementById('gw99Clock');
      if (!el) { this._gw99StopClock(); return; }
      const s = Math.floor((Date.now() - this._gw99T0) / 1000);
      const hh = Math.floor(s / 3600), mm = Math.floor((s % 3600) / 60), ss = s % 60;
      el.textContent = [hh, mm, ss].map(v => String(v).padStart(2, '0')).join(':');
    } catch (e) { this._gw99StopClock(); }
  },
  _gw99StopClock() {
    if (this._gw99Timer) { clearInterval(this._gw99Timer); this._gw99Timer = null; }
  },
  // 离开阅读视图时结算：累计阅读秒数（本次会话 + 历史累计）
  _gw99Settle() {
    try {
      this._gw99StopClock();
      const book = this._gw99CurBook();
      if (!book || !this._gw99T0) { this._gw99T0 = 0; return; }
      const add = Math.floor((Date.now() - this._gw99T0) / 1000);
      this._gw99T0 = 0;
      if (add <= 0) return;
      const prog = this._gw99Progress();
      const key = this._gw99Shelf + '_' + book.id;
      const p = prog[key] || { flat: 0, sec: 0 };
      p.sec = (p.sec || 0) + add;
      p.flat = this._gw99Flat;
      p.last = Date.now();
      const day = (typeof Store !== 'undefined' && Store.today) ? Store.today() : String(Date.now()).slice(0, 10);
      p.days = p.days || {};
      p.days[day] = (p.days[day] || 0) + add;
      prog[key] = p;
      this._gw99ProgressSave(prog);
    } catch (e) {}
  },
