          const gi = this._gw99GlobalIdx(book, si, pi);
          const on = gi === this._gw99Flat;
          const done = gi < this._gw99Flat;
          return `<div class="gw-toc-item${on ? ' on' : ''}${done ? ' done' : ''}" onclick="App._gw99Jump(${gi})">${done ? '✓ ' : ''}${this.esc(p.t)}</div>`;
